-- A link is a file whose bytes live somewhere else.
--
-- The docs tool holds three things people think of as different — a document
-- written here, a file uploaded here, and a link to something kept elsewhere —
-- and all three are the same row with a different place to read from. `body`
-- means written, `storage_key` means uploaded, `url` means elsewhere.
--
-- The alternative was a fifth entity, which the design refuses by name. It
-- would also mean a fourth set of comment, version and client-visibility
-- rules, and the one that gets them subtly wrong is the one facing the client.
alter table file add column url text;
