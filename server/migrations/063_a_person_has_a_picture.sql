-- A person's picture, the way a project's is.
--
-- `avatar_url` has been on `actor` since the first migration and nothing has
-- ever written to it. It is left alone rather than dropped: a text column
-- nobody reads costs nothing, and dropping one is a migration that can fail
-- on a database somebody has already filled in by hand.
--
-- The key is what is new. A project keeps `icon_key` and the bytes live
-- behind short-lived signed links — `storage.ts` opens by saying there are no
-- public URLs, and a column called `avatar_url` is an invitation to put one
-- there. The API still answers with a field of that name; it is computed from
-- this key now, the way `icon_url` already is.
alter table actor add column if not exists avatar_key text;
